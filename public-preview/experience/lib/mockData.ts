function seedRoom(no: string, state: RoomState): RoomRecord {
  const base = { no, floor: Number(no[0]), note: undefined as string | undefined };
  switch (state) {
    case 'O':
      return { ...base, occupied: true, readiness: 'ready', dnd: false };
    case 'L':
      return { ...base, occupied: true, readiness: 'ready', dnd: true };
    case 'D':
      return { ...base, occupied: false, readiness: 'dirty', dnd: false };
    case 'X':
      return { ...base, occupied: false, readiness: 'out_of_order', dnd: false, note: 'Blocked in PMS · approved by Duty Manager' };
    case 'V':
      return { ...base, occupied: false, readiness: 'ready', dnd: false };
  }
}

